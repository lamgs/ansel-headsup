// Summary tab: a calm, document-style read. "Open last meeting" lands here.
// Every item and theme links into the transcript.
import React, { useEffect, useState } from 'react'
import { Circle, CircleCheck, FileText, Pencil } from 'lucide-react'
import { useStore } from '../../state/store.jsx'
import { shortDate } from '../../logic/buildHeadsUp.js'
import { Avatar, Btn, Ts, firstName, fmtClock, personName } from '../../components/ui.jsx'
import { StatusPill, jumpTo } from './shared.jsx'

export default function SummaryTab({ inst, series }) {
  const { state, dispatch } = useStore()
  const isOrganizer = state.persona === series.organizer
  const [flash, setFlash] = useState(null)

  // The card's "Edited" badge focuses a line here.
  useEffect(() => {
    if (!state.ansel.focusId) return
    document.getElementById(`sum-${state.ansel.focusId}`)?.scrollIntoView({ block: 'center' })
    setFlash(state.ansel.focusId)
    const t = setTimeout(() => { setFlash(null); dispatch({ type: 'ANSEL_NAV', nav: { focusId: null } }) }, 3000)
    return () => clearTimeout(t)
  }, [state.ansel.focusId])

  return (
    <article className="max-w-[680px] px-6 py-8">
      <div className="flex items-start justify-between gap-4">
        <p className="text-xs text-slate-500">Summary generated by Ansel 6 min after the meeting · {inst.attendees.length} attendees</p>
        <Btn onClick={() => jumpTo(dispatch, null)}><FileText size={15} aria-hidden />View full transcript</Btn>
      </div>

      <H>Decisions</H>
      {inst.decisions.length === 0 ? <None /> : (
        <ul className="space-y-1">
          {inst.decisions.map((d) => <Bullet key={d.id} it={d} editable={isOrganizer} flash={flash === d.id} inst={inst} />)}
        </ul>
      )}

      <H>Open questions</H>
      {inst.openQuestions.length === 0 ? <None /> : (
        <ul className="space-y-1">
          {inst.openQuestions.map((q) => <Bullet key={q.id} it={q} editable={isOrganizer} flash={flash === q.id} inst={inst} />)}
        </ul>
      )}

      <H>Action items</H>
      {inst.actionItems.length === 0 ? <None /> : (
        <ul className="divide-y divide-slate-100 dark:divide-slate-800">
          {inst.actionItems.map((a) => <ActionRow key={a.id} a={a} flash={flash === a.id} />)}
        </ul>
      )}

      <H>Themes</H>
      {(inst.themes || []).length === 0 ? <None /> : (
        <ul className="space-y-1">
          {inst.themes.map((th) => (
            <li key={th.id} className="flex items-baseline gap-3 rounded-md px-2 py-1.5 hover:bg-slate-50 dark:hover:bg-slate-900">
              <button onClick={() => jumpTo(dispatch, th.start, { theme: th.id })} className="flex-1 text-left text-[15px] hover:text-ansel dark:hover:text-ansel-300">{th.title}</button>
              <span className="text-xs text-slate-400">{th.items.length ? `${th.items.length} item${th.items.length > 1 ? 's' : ''} · ` : ''}{th.start}–{th.end}</span>
              <Ts t={th.start} onClick={() => jumpTo(dispatch, th.start, { theme: th.id })} />
            </li>
          ))}
        </ul>
      )}
    </article>
  )
}

const H = ({ children }) => <h2 className="mb-2 mt-8 text-sm font-semibold uppercase tracking-wider text-slate-500">{children}</h2>
const None = () => <p className="text-sm text-slate-400">None.</p>

function Bullet({ it, editable, flash, inst }) {
  const { state, dispatch } = useStore()
  const [editing, setEditing] = useState(false)
  const [draft, setDraft] = useState(it.text)
  const [commenting, setCommenting] = useState(false)
  const [comment, setComment] = useState('')
  const comments = state.comments[it.id] || []
  const tc = it.trackedChange
  const canComment = !editable && inst.attendees.includes(state.persona)
  return (
    <li id={`sum-${it.id}`} className={`group flex items-start gap-2 rounded-md px-2 py-1.5 ${flash ? 'flash' : ''}`}>
      <span className="mt-2.5 h-1.5 w-1.5 shrink-0 rounded-full bg-slate-400" />
      <div className="min-w-0 flex-1 text-[15px] leading-7">
        {editing ? (
          <div className="flex gap-2">
            <input autoFocus value={draft} onChange={(e) => setDraft(e.target.value)} className="flex-1 rounded border border-slate-300 bg-transparent px-2 py-1 text-sm dark:border-slate-600" />
            <Btn variant="primary" onClick={() => { if (draft.trim() && draft !== it.text) dispatch({ type: 'EDIT', id: it.id, text: draft.trim() }); setEditing(false) }}>Save</Btn>
            <Btn variant="ghost" onClick={() => { setDraft(it.text); setEditing(false) }}>Cancel</Btn>
          </div>
        ) : (
          <>
            {tc && <span className="mr-2 text-slate-400 line-through">{tc.original}</span>}
            <span className={tc ? 'rounded bg-emerald-50 px-0.5 dark:bg-emerald-500/10' : ''}>{it.text}</span>
            {it.status === 'resolved' && <span className="ml-2 text-xs text-emerald-600">Resolved {it.resolvedIn === 'wps-1106' ? 'Nov 6' : ''}</span>}
            {tc && <div className="text-xs leading-5 text-amber-700 dark:text-amber-400">Edited · {firstName(tc.by)} · {shortDate(tc.on)}</div>}
          </>
        )}
        {comments.map((c, i) => <div key={i} className="mt-1 rounded bg-slate-50 px-2 py-1 text-xs leading-5 dark:bg-slate-900"><b>{firstName(c.by)}</b> {c.text} <span className="text-slate-400">· {fmtClock(c.sec)}</span></div>)}
        {commenting && (
          <div className="mt-2 flex gap-2">
            <input autoFocus value={comment} onChange={(e) => setComment(e.target.value)} placeholder="Add a comment" className="flex-1 rounded border border-slate-300 bg-transparent px-2 py-1 text-xs dark:border-slate-600" />
            <Btn onClick={() => { if (comment.trim()) dispatch({ type: 'COMMENT', id: it.id, text: comment.trim() }); setComment(''); setCommenting(false) }}>Comment</Btn>
          </div>
        )}
      </div>
      {editable && !editing && <button title="Edit (saved as a tracked change)" onClick={() => setEditing(true)} className="mt-1 rounded p-1 text-slate-400 hover:bg-slate-100 hover:text-slate-700 dark:hover:bg-slate-800"><Pencil size={14} /></button>}
      {canComment && !commenting && <button onClick={() => setCommenting(true)} className="mt-1 rounded px-1 text-xs text-slate-500 opacity-0 hover:bg-slate-100 group-hover:opacity-100 dark:hover:bg-slate-800">Comment</button>}
      <Ts t={it.t} className="mt-1" onClick={() => jumpTo(dispatch, it.t, { item: it.id })} />
    </li>
  )
}

function ActionRow({ a, flash }) {
  const { state, dispatch } = useStore()
  const done = a.status === 'done'
  return (
    <li id={`sum-${a.id}`} className={`flex items-start gap-3 px-2 py-2.5 ${flash ? 'flash' : ''}`}>
      {done ? <CircleCheck size={18} className="mt-0.5 shrink-0 text-emerald-600" aria-label="Done" /> : <Circle size={18} className="mt-0.5 shrink-0 text-slate-300 dark:text-slate-600" aria-label="Open" />}
      <div className="min-w-0 flex-1">
        <div className={`text-[15px] ${done ? 'text-slate-500 line-through' : ''}`}>{a.text}</div>
        <div className="mt-1 flex flex-wrap items-center gap-2 text-xs text-slate-500">
          <Avatar id={a.owner} size="xs" />{personName(a.owner)} · due {shortDate(a.due)} <StatusPill a={a} />
        </div>
      </div>
      {a.owner === state.persona && !done && (
        <button onClick={() => dispatch({ type: 'ANSEL_NAV', nav: { panelItem: a.id } })} className="mt-0.5 text-xs font-medium text-ansel dark:text-ansel-300">Update</button>
      )}
      <Ts t={a.t} onClick={() => jumpTo(dispatch, a.t, { item: a.id })} />
    </li>
  )
}
